import chalk from 'chalk';
import { SynapseApi } from '../api';
import { loadConfig } from '../config';

export async function showCommand(nodeIdOrDisplayId: string) {
  const cfg = loadConfig();
  if (!cfg.project) {
    console.log(chalk.yellow('Run `synapse init` first!'));
    return;
  }

  const api = new SynapseApi();
  try {
    const nodes = await api.listNodes(cfg.project);
    const target = nodes.find(
      (n) => n.display_id.toUpperCase() === nodeIdOrDisplayId.toUpperCase() || n.id === nodeIdOrDisplayId
    );

    if (!target) {
      console.log(chalk.red(`Node ${nodeIdOrDisplayId} not found in this project.`));
      return;
    }

    console.log(chalk.cyan.bold(`\n???????????????????????????????????????????????????????????????`));
    console.log(chalk.cyan.bold(`?  [${target.display_id}]  ${target.type.toUpperCase()}  ?  ${target.title}`));
    console.log(chalk.cyan.bold(`?  Status: ${target.status || 'draft'}     Updated: ${new Date(target.updated_at).toLocaleDateString()}`));
    console.log(chalk.cyan.bold(`???????????????????????????????????????????????????????????????`));
    if (target.content) {
      console.log(`\n${target.content}\n`);
    }
    if (target.tags && target.tags.length > 0) {
      console.log(chalk.dim(`Tags: ${target.tags.map((t) => '#' + t).join(' ')}`));
    }
    console.log(chalk.cyan.bold(`???????????????????????????????????????????????????????????????\n`));
  } catch (err: any) {
    console.error(chalk.red(`? Failed to show node: ${err.message}`));
  }
}
